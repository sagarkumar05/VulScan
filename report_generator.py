import os
import json
from datetime import datetime
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import cm
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table,
    TableStyle, HRFlowable
)


def generate_report(results: dict, report_dir: str = "reports") -> dict:
    os.makedirs(report_dir, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    target_safe = (
        results.get("target", "unknown")
        .replace("http://", "").replace("https://", "")
        .replace("/", "_").replace(":", "_")
    )

    pdf_path  = os.path.join(report_dir, f"report_{target_safe}_{timestamp}.pdf")
    json_path = os.path.join(report_dir, f"report_{target_safe}_{timestamp}.json")

    # JSON report
    with open(json_path, "w", encoding="utf-8") as jf:
        json.dump(results, jf, indent=4, default=str)

    # PDF report generater
    _generate_pdf(results, pdf_path)

    return {"pdf": pdf_path, "json": json_path}


def _generate_pdf(results: dict, pdf_path: str):
    doc = SimpleDocTemplate(
        pdf_path,
        pagesize=A4,
        rightMargin=2 * cm, leftMargin=2 * cm,
        topMargin=2 * cm, bottomMargin=2 * cm
    )

    styles = getSampleStyleSheet()
    # font size and color
    title_style = ParagraphStyle(
        "CustomTitle",
        parent=styles["Title"],
        fontSize=22,
        textColor=colors.HexColor("#1a1a2e"),
        spaceAfter=6,
    )
    heading_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontSize=13,
        textColor=colors.HexColor("#16213e"),
        spaceBefore=12, spaceAfter=4,
        borderPad=4,
    )
    normal_style = styles["Normal"]
    normal_style.fontSize = 10

    story = []

    # Title Page 
    story.append(Paragraph("🔒 Web Vulnerability Scan Report", title_style))
    story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#e94560")))
    story.append(Spacer(1, 0.3 * cm))

    meta = [
        ["Target",    results.get("target", "N/A")],
        ["Scan Time", results.get("scan_time", "N/A")],
        ["Risk Level", results.get("overall_risk", "N/A")],
    ]
    meta_table = Table(meta, colWidths=[4 * cm, 12 * cm])
    meta_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#1a1a2e")),
        ("TEXTCOLOR",  (0, 0), (0, -1), colors.white),
        ("FONTNAME",   (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE",   (0, 0), (-1, -1), 10),
        ("GRID",       (0, 0), (-1, -1), 0.5, colors.grey),
        ("ROWBACKGROUNDS", (1, 0), (-1, -1), [colors.HexColor("#f5f5f5"), colors.white]),
        ("VALIGN",     (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 0.5 * cm))

    # ── Each module section ───────────────────────────────────────────────────
    section_map = {
        "url_ip":      ("🌐 URL & IP Information",    _format_url_ip),
        "ports":       ("🔌 Open Ports",               _format_ports),
        "subdomains":  ("🗺️  Subdomains Found",        _format_subdomains),
        "ssl":         ("🔐 SSL/TLS Analysis",         _format_ssl),
        "sql":         ("💉 SQL Injection Results",    _format_generic_vulns),
        "xss":         ("⚡ XSS Results",              _format_generic_vulns),
        "risk":        ("⚠️  Risk Assessment",         _format_risk),
    }

    for key, (heading, formatter) in section_map.items():
        if key in results and results[key]:
            story.append(Paragraph(heading, heading_style))
            story.append(HRFlowable(width="100%", thickness=0.5, color=colors.lightgrey))
            story.append(Spacer(1, 0.2 * cm))
            formatted = formatter(results[key], normal_style)
            story.extend(formatted)
            story.append(Spacer(1, 0.4 * cm))

    # ── Footer ────────────────────────────────────────────────────────────────
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#e94560")))
    story.append(Paragraph(
        "Generated by VulnScanner — B.Tech Final Year Project | Develop By Majid Ansari",
        ParagraphStyle("Footer", parent=normal_style, fontSize=8, textColor=colors.grey)
    ))

    doc.build(story)


# Section formatters

def _format_url_ip(data: dict, style) -> list:
    rows = [[k, str(v)] for k, v in data.items()]
    return [_make_table(rows)]


def _format_ports(data: dict, style) -> list:
    open_ports = data.get("open_ports", [])
    if not open_ports:
        return [Paragraph("No open ports found.", style)]
    rows = [["Port", "Status", "Service"]] + [
        [str(p["port"]), p.get("status", "open"), p.get("service", "unknown")]
        for p in open_ports
    ]
    return [_make_table(rows, header=True)]


def _format_subdomains(data: dict, style) -> list:
    found = data.get("found", [])
    if not found:
        return [Paragraph("No subdomains discovered.", style)]
    rows = [["Subdomain", "IP"]] + [[s.get("subdomain", ""), s.get("ip", "")] for s in found]
    return [_make_table(rows, header=True)]


def _format_ssl(data: dict, style) -> list:
    rows = [[k, str(v)] for k, v in data.items() if k != "errors"]
    flowables = [_make_table(rows)]
    if data.get("errors"):
        flowables.append(Paragraph(f"⚠ Errors: {'; '.join(data['errors'])}", style))
    return flowables


def _format_generic_vulns(data: dict, style) -> list:
    vulnerable = data.get("vulnerable", False)
    findings   = data.get("findings", [])
    color_text = "🔴 VULNERABLE" if vulnerable else "🟢 Not Vulnerable"
    flowables  = [Paragraph(color_text, style)]
    if findings:
        rows = [["URL / Parameter", "Payload", "Evidence"]]
        for f in findings:
            rows.append([
                str(f.get("url", f.get("parameter", ""))),
                str(f.get("payload", "")),
                str(f.get("evidence", ""))[:80]
            ])
        flowables.append(_make_table(rows, header=True))
    return flowables


def _format_risk(data: dict, style) -> list:
    rows = [
        ["Overall Risk", data.get("overall_risk", "N/A")],
        ["Score",        str(data.get("score", 0))],
        ["Open Ports",   str(data.get("open_ports_count", 0))],
        ["Subdomains",   str(data.get("subdomains_count", 0))],
        ["SQL Vuln",     "Yes" if data.get("sql_vulnerable") else "No"],
        ["XSS Vuln",     "Yes" if data.get("xss_vulnerable") else "No"],
        ["SSL Issues",   "Yes" if data.get("ssl_issues") else "No"],
    ]
    flowables = [_make_table(rows)]
    recommendations = data.get("recommendations", [])
    if recommendations:
        flowables.append(Spacer(1, 0.2 * cm))
        flowables.append(Paragraph("<b>Recommendations:</b>", style))
        for rec in recommendations:
            flowables.append(Paragraph(f"• {rec}", style))
    return flowables


def _make_table(rows: list, header: bool = False) -> Table:
    """Generic 2-column table with optional colored header row."""
    col_count = max(len(r) for r in rows) if rows else 2
    col_width = 16 / col_count
    t = Table(rows, colWidths=[col_width * cm] * col_count)
    style_cmds = [
        ("FONTNAME",      (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE",      (0, 0), (-1, -1), 9),
        ("GRID",          (0, 0), (-1, -1), 0.4, colors.HexColor("#cccccc")),
        ("ROWBACKGROUNDS",(0, 0), (-1, -1), [colors.HexColor("#f9f9f9"), colors.white]),
        ("VALIGN",        (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING",    (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LEFTPADDING",   (0, 0), (-1, -1), 6),
    ]
    if header:
        style_cmds += [
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1a1a2e")),
            ("TEXTCOLOR",  (0, 0), (-1, 0), colors.white),
            ("FONTNAME",   (0, 0), (-1, 0), "Helvetica-Bold"),
        ]
    t.setStyle(TableStyle(style_cmds))
    return t
